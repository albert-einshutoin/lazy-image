/**
 * Regression coverage for keeping codec bake-off benchmarks aligned with
 * malformed fuzz seed coverage.
 */

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const { resolveRoot, resolveTemp } = require('../helpers/paths');
const {
  AVIF_BACKEND_BAKEOFF_CASES,
  FUZZ_TARGET_SEED_COVERAGE,
  JPEG_BACKEND_BAKEOFF_CASES,
  buildBakeoffCorpusExpectations,
} = require('../helpers/codec-bakeoff-cases');

const SEED_SCRIPT = resolveRoot('scripts/fuzz/write-seed-corpus.mjs');
const CORPUS_ROOT = resolveTemp(`benchmark-fuzz-alignment-${process.pid}`);

let passed = 0;
let failed = 0;

function report(name, error) {
  if (error) {
    console.log(`not ok - ${name}`);
    console.log(`   Error: ${error.message}`);
    failed += 1;
  } else {
    console.log(`ok - ${name}`);
    passed += 1;
  }
}

function test(name, fn) {
  try {
    fn();
    report(name);
  } catch (error) {
    report(name, error);
  }
}

function resetCorpusRoot() {
  fs.rmSync(CORPUS_ROOT, { recursive: true, force: true });
}

function generateCorpus() {
  const result = spawnSync(process.execPath, [
    SEED_SCRIPT,
    '--corpus-root',
    CORPUS_ROOT,
  ], {
    cwd: resolveRoot(),
    encoding: 'utf8',
  });

  assert.equal(result.status, 0, result.stderr || result.stdout);
}

function collectGeneratedSeeds() {
  const seedsByTarget = new Map();

  for (const target of fs.readdirSync(CORPUS_ROOT).sort()) {
    const targetDir = path.join(CORPUS_ROOT, target);
    seedsByTarget.set(target, new Set(fs.readdirSync(targetDir).sort()));
  }

  return seedsByTarget;
}

function allBakeoffCases() {
  return [
    ...JPEG_BACKEND_BAKEOFF_CASES,
    ...AVIF_BACKEND_BAKEOFF_CASES,
  ];
}

function requiredFuzzTargets() {
  return [
    ...new Set(allBakeoffCases().flatMap((testCase) => testCase.fuzzTargets || [])),
  ].sort();
}

console.log('=== Benchmark/Fuzz Alignment Tests ===\n');

try {
  resetCorpusRoot();
  generateCorpus();
  const generatedSeeds = collectGeneratedSeeds();

  test('codec bake-off cases declare malformed fuzz targets', () => {
    for (const testCase of allBakeoffCases()) {
      assert.notEqual(testCase.fuzzTargets, undefined, `${testCase.label} must declare fuzzTargets`);
      assert.notEqual(testCase.fuzzTargets.length, 0, `${testCase.label} must require at least one fuzz target`);

      const expectations = buildBakeoffCorpusExpectations(testCase);
      assert.match(expectations.fuzzTargets, /\w+/, `${testCase.label} must expose fuzz targets in artifacts`);
    }
  });

  test('declared bake-off fuzz targets exist in the generated malformed seed corpus', () => {
    for (const target of requiredFuzzTargets()) {
      assert.ok(generatedSeeds.has(target), `${target} target must be generated by ${path.basename(SEED_SCRIPT)}`);
      assert.ok(generatedSeeds.get(target).size > 0, `${target} target must include at least one malformed seed`);
    }
  });

  test('declared bake-off fuzz targets keep the expected seed families', () => {
    for (const target of requiredFuzzTargets()) {
      const requiredSeeds = FUZZ_TARGET_SEED_COVERAGE[target];
      assert.ok(requiredSeeds, `${target} must have seed coverage expectations`);

      for (const seed of requiredSeeds) {
        assert.ok(generatedSeeds.get(target).has(seed), `${target} must include ${seed}`);
      }
    }
  });
} finally {
  resetCorpusRoot();
}

console.log(`\nTests passed: ${passed}, failed: ${failed}`);
if (failed > 0) {
  process.exit(1);
}
